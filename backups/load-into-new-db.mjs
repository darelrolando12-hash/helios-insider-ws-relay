/**
 * Load the exported NDJSON into the new Supabase project over Postgres.
 *
 * Runs after schema.sql and permissions.sql. Ordering matters: signals must
 * land before signal_outcomes, because signal_outcomes.signal_id references
 * it — the one foreign key the source spec declares.
 *
 * Inserts preserve the original primary keys rather than generating new ones.
 * That is not cosmetic: signal_outcomes.signal_id holds values like
 * "bt_1_MSTR_1788984035610", and renumbering signals would silently orphan
 * 16,223 outcome rows. The three tables with numeric sequences are declared
 * `generated by default as identity` for exactly this reason, and their
 * sequences are advanced past the loaded maximum afterwards so the next
 * engine insert does not collide.
 *
 * Every table is verified against its source row count at the end. A short
 * load fails loudly rather than leaving a quietly incomplete database.
 *
 *   PGURL='postgresql://...' node backups/load-into-new-db.mjs <exportDir> [table ...]
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

// `pg` deliberately lives outside this repo. Adding it to package.json would
// change pnpm-lock.yaml, and Vercel builds the frontend from that lockfile —
// a migration-only dependency has no business in the production bundle.
// PG_MODULE_DIR points at the scratch install.
const pgDir = process.env.PG_MODULE_DIR;
if (!pgDir) { console.error('PG_MODULE_DIR must point at a directory containing node_modules/pg'); process.exit(1); }
const pg = createRequire(path.join(pgDir, 'noop.cjs'))('pg');

const PGURL = process.env.PGURL;
const dir = process.argv[2];
if (!PGURL || !dir) { console.error('usage: PGURL=... load-into-new-db.mjs <exportDir> [table ...]'); process.exit(1); }

/** signals before signal_outcomes — the FK depends on it. */
const ORDER = [
  'signals', 'signal_outcomes', 'signal_snapshots',
  'gex_regime_log', 'engine_shadow_signals',
  'ticker_win_rates', 'user_watchlist', 'ticker_allowlist',
  'insider_transactions', 'short_interest', 'short_volume',
  'financial_ratios', 'sec_filings_8k', 'sec_filings_13f',
  'earnings_calendar', 'bars_gap_report', 'luld_events', 'news_headlines',
];
const IDENTITY_TABLES = ['signal_outcomes', 'gex_regime_log', 'engine_shadow_signals'];

/**
 * First moment a browser carrying the session-scoped CVD fix served users:
 * the Vercel production deploy of f420df1. Signals written before this were
 * scored by the Wegic frontend, which never received that fix, so their
 * 25-point CVD factor read flow accumulated since process boot rather than
 * since the session open. See EXTRA_COLUMNS in generate-schema.mjs.
 */
const CVD_FIX_LIVE_AT_MS = 1789448855426; // 2026-09-15T05:07:35.426Z

/** Columns this migration computes rather than copies. */
function derived(table, row) {
  if (table !== 'signals') return {};
  const t = Number(row.entry_utc);
  // Unparseable entry_utc is marked contaminated rather than assumed clean:
  // the safe direction on ambiguity is to withhold trust, not extend it.
  return { pre_cvd_fix: !Number.isFinite(t) || t < CVD_FIX_LIVE_AT_MS };
}

const requested = process.argv.slice(3);
const tables = (requested.length ? requested : ORDER)
  .filter(t => fs.existsSync(path.join(dir, `${t}.ndjson`)));

const client = new pg.Client({ connectionString: PGURL, ssl: { rejectUnauthorized: false } });
await client.connect();

const BATCH = 500;
const report = [];

for (const table of tables) {
  const file = path.join(dir, `${table}.ndjson`);
  const rows = fs.readFileSync(file, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l));
  if (rows.length === 0) { report.push({ table, expected: 0, loaded: 0, ok: true }); console.log(`  OK   ${table.padEnd(24)} 0 rows (empty)`); continue; }

  const cols = [...Object.keys(rows[0]), ...Object.keys(derived(table, rows[0]))];
  const colSql = cols.map(c => `"${c}"`).join(', ');

  let loaded = 0;
  for (let i = 0; i < rows.length; i += BATCH) {
    const slice = rows.slice(i, i + BATCH);
    const values = [];
    const placeholders = slice.map((r, ri) => {
      const ph = cols.map((c, ci) => `$${ri * cols.length + ci + 1}`);
      const row = { ...r, ...derived(table, r) };
      for (const c of cols) {
        const v = row[c];
        // jsonb and array columns must go in as JSON text / JS arrays, not "[object Object]"
        values.push(v !== null && typeof v === 'object' && !Array.isArray(v) ? JSON.stringify(v) : v);
      }
      return `(${ph.join(', ')})`;
    }).join(', ');

    const sql = `insert into public."${table}" (${colSql}) values ${placeholders} on conflict do nothing`;
    const res = await client.query(sql, values);
    loaded += res.rowCount;
  }

  const { rows: [{ count }] } = await client.query(`select count(*)::int as count from public."${table}"`);
  const ok = count === rows.length;
  report.push({ table, expected: rows.length, loaded: count, ok });
  console.log(`  ${ok ? 'OK  ' : 'FAIL'} ${table.padEnd(24)} ${String(count).padStart(7)} / ${String(rows.length).padEnd(7)} (inserted ${loaded})`);
}

// Advance identity sequences past what we just inserted, or the engine's next
// insert collides with a migrated row.
console.log('\n=== resetting identity sequences ===');
for (const t of IDENTITY_TABLES) {
  if (!tables.includes(t)) continue;
  const { rows: [r] } = await client.query(
    `select setval(pg_get_serial_sequence('public."${t}"','id'), coalesce((select max(id) from public."${t}"), 1), true) as newval`
  );
  console.log(`  ${t.padEnd(24)} sequence -> ${r.newval}`);
}

await client.end();

const failed = report.filter(r => !r.ok);
const total = report.reduce((a, r) => a + r.loaded, 0);
console.log(`\ntotal rows in new database: ${total}`);
if (failed.length) {
  console.error(`INCOMPLETE — ${failed.map(f => `${f.table} ${f.loaded}/${f.expected}`).join(', ')}`);
  process.exit(1);
}
console.log('every table matches its exported row count.');
