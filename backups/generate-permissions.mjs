/**
 * Permissions for the reconstructed schema.
 *
 * This is the part the OpenAPI spec cannot give us at all: RLS policies and
 * grants are invisible over PostgREST, so every rule below is reconstructed
 * from how the system actually uses each table, and each is labelled with
 * where it came from.
 *
 * Two hard lessons from the source database are baked in:
 *
 *  1. REVOKE BEFORE GRANT. Supabase's project bootstrap runs
 *     `ALTER DEFAULT PRIVILEGES ... GRANT ALL ON TABLES TO anon` on public,
 *     which applies to every new table before any migration-specific grant
 *     runs. Postgres privileges are additive, so a narrow GRANT cannot undo
 *     it — only an explicit REVOKE can. Found 2026-09-13 when anon turned out
 *     to hold DELETE/TRUNCATE/UPDATE on tables whose DDL granted far less.
 *
 *  2. RLS OFF MEANS OPEN, NOT CLOSED. A table with RLS disabled is reachable
 *     by anyone holding the anon key, which ships in the browser bundle by
 *     design. Every table therefore enables RLS explicitly.
 *
 * The engine authenticates with the anon key (it has no service-role key —
 * see CLAUDE.md), so ingestion tables must grant anon the writes the engine
 * performs. That is a faithful reproduction of today's model, not an
 * endorsement of it; moving the engine to the service-role key on the new
 * project would be a genuine improvement and is called out in the report.
 */
import fs from 'node:fs';

const specPath = process.argv[2];
const outPath = process.argv[3];
if (!specPath || !outPath) { console.error('usage: generate-permissions.mjs <openapi.json> <out.sql>'); process.exit(1); }
const defs = JSON.parse(fs.readFileSync(specPath, 'utf8')).definitions || {};

/**
 * Engine-written reference and market data. The engine upserts these with the
 * anon key, and the browser reads them. Delete is withheld everywhere except
 * the tables whose ingestion genuinely prunes rows.
 */
const INGESTION = [
  'bars_1m', 'bars_daily', 'bars_gap_report', 'daily_high_low', 'earnings_calendar',
  'financial_ratios', 'insider_transactions', 'luld_events', 'news_headlines',
  'sec_filings_13f', 'sec_filings_8k', 'short_interest', 'short_volume',
  'ticker_allowlist', 'ticker_win_rates', 'stock_float',
];
/** These have a real delete path in the code (.delete() observed in the query scan). */
const DELETERS = new Set(['daily_high_low', 'short_interest', 'short_volume', 'ticker_allowlist']);

const out = [];
const P = (s) => out.push(s);

P('-- Permissions for the reconstructed Helios schema.');
P('-- Generated by backups/generate-permissions.mjs — see that file for provenance.');
P(`-- Generated: ${new Date().toISOString()}`);
P('');
P('begin;');
P('');

for (const t of Object.keys(defs).sort()) {
  P(`-- ${t}`);
  P(`alter table public."${t}" enable row level security;`);
  P(`revoke all on public."${t}" from anon;`);
  P(`revoke all on public."${t}" from authenticated;`);
}
P('');

// ── Ingestion / reference tables ────────────────────────────────────────────
P('-- Engine-written reference data: the engine upserts with the anon key, so');
P('-- anon needs select+insert+update here. Delete only where ingestion prunes.');
for (const t of INGESTION) {
  if (!defs[t]) continue;
  const del = DELETERS.has(t) ? ', delete' : '';
  P(`grant select, insert, update${del} on public."${t}" to anon;`);
  P(`drop policy if exists "${t}_anon_read" on public."${t}";`);
  P(`create policy "${t}_anon_read" on public."${t}" for select to anon using (true);`);
  P(`drop policy if exists "${t}_anon_write" on public."${t}";`);
  P(`create policy "${t}_anon_write" on public."${t}" for insert to anon with check (true);`);
  P(`drop policy if exists "${t}_anon_update" on public."${t}";`);
  P(`create policy "${t}_anon_update" on public."${t}" for update to anon using (true) with check (true);`);
  if (DELETERS.has(t)) {
    P(`drop policy if exists "${t}_anon_delete" on public."${t}";`);
    P(`create policy "${t}_anon_delete" on public."${t}" for delete to anon using (true);`);
  }
  P('');
}

// ── signals ─────────────────────────────────────────────────────────────────
P('-- signals: update is restricted to the one real state transition');
P('-- (pending -> resolved/expired), mirroring the source policy described in');
P('-- CLAUDE.md. No delete policy: with RLS on and no policy, delete affects 0');
P('-- rows regardless of grant.');
P('grant select, insert, update on public."signals" to anon;');
P('drop policy if exists "signals_anon_read" on public."signals";');
P('create policy "signals_anon_read" on public."signals" for select to anon using (true);');
P('drop policy if exists "signals_anon_insert" on public."signals";');
P('create policy "signals_anon_insert" on public."signals" for insert to anon with check (true);');
P('drop policy if exists "signals_anon_update" on public."signals";');
P('create policy "signals_anon_update" on public."signals" for update to anon');
P("  using (status = 'pending')");
P("  with check (status in ('resolved','expired'));");
P('');

// ── signal_outcomes ─────────────────────────────────────────────────────────
P('-- signal_outcomes: this is the ground truth behind every Brain win rate and');
P('-- every backtest-vs-forward comparison. The source table was found with an');
P('-- unconditioned update policy (2026-09-13) that let any anon-key holder');
P('-- rewrite pnl_pct/result/exit_price on any resolved outcome.');
P('-- outcomeResolver writes every column on every call, so column-scoping does');
P('-- not work here; the fix mirrors signals own state machine instead — a write');
P('-- is allowed only while the PARENT signal is still pending, which is exactly');
P("-- outcomeResolver's own precondition (it only queries WHERE status='pending',");
P('-- and a signal never returns to pending once resolved).');
P('grant select, insert, update on public."signal_outcomes" to anon;');
P('drop policy if exists "signal_outcomes_anon_read" on public."signal_outcomes";');
P('create policy "signal_outcomes_anon_read" on public."signal_outcomes" for select to anon using (true);');
P('drop policy if exists "signal_outcomes_anon_insert" on public."signal_outcomes";');
P('create policy "signal_outcomes_anon_insert" on public."signal_outcomes" for insert to anon with check (true);');
P('drop policy if exists "signal_outcomes_update" on public."signal_outcomes";');
P('create policy "signal_outcomes_update" on public."signal_outcomes" for update to anon');
P('  using (exists (select 1 from public."signals" s');
P("                 where s.id = signal_outcomes.signal_id and s.status = 'pending'))");
P('  with check (exists (select 1 from public."signals" s');
P("                      where s.id = signal_outcomes.signal_id and s.status = 'pending'));");
P('');

// ── observation tables ──────────────────────────────────────────────────────
P('-- gex_regime_log: an append-only observation record whose whole purpose is');
P('-- to be un-rewritable after the fact. Update is scoped to the two forward-');
P('-- return columns that settleOutcomes fills in later, and nothing else —');
P('-- flip_level/spot/gex_regime/observed_at must never be editable.');
P('grant select, insert on public."gex_regime_log" to anon;');
P('grant update ("fwd_30m_pct", "fwd_60m_pct") on public."gex_regime_log" to anon;');
P('drop policy if exists "gex_regime_log_anon_read" on public."gex_regime_log";');
P('create policy "gex_regime_log_anon_read" on public."gex_regime_log" for select to anon using (true);');
P('drop policy if exists "gex_regime_log_anon_insert" on public."gex_regime_log";');
P('create policy "gex_regime_log_anon_insert" on public."gex_regime_log" for insert to anon with check (true);');
P('drop policy if exists "gex_regime_log_anon_settle" on public."gex_regime_log";');
P('create policy "gex_regime_log_anon_settle" on public."gex_regime_log" for update to anon');
P('  using (fwd_30m_pct is null or fwd_60m_pct is null) with check (true);');
P('');
P('-- engine_shadow_signals: append-only. No update path exists in the writer,');
P('-- so none is granted.');
P('grant select, insert on public."engine_shadow_signals" to anon;');
P('drop policy if exists "engine_shadow_signals_anon_read" on public."engine_shadow_signals";');
P('create policy "engine_shadow_signals_anon_read" on public."engine_shadow_signals" for select to anon using (true);');
P('drop policy if exists "engine_shadow_signals_anon_insert" on public."engine_shadow_signals";');
P('create policy "engine_shadow_signals_anon_insert" on public."engine_shadow_signals" for insert to anon with check (true);');
P('');
P('-- signal_snapshots: append-only record of what a signal was made of.');
P('grant select, insert on public."signal_snapshots" to anon;');
P('drop policy if exists "signal_snapshots_anon_read" on public."signal_snapshots";');
P('create policy "signal_snapshots_anon_read" on public."signal_snapshots" for select to anon using (true);');
P('drop policy if exists "signal_snapshots_anon_insert" on public."signal_snapshots";');
P('create policy "signal_snapshots_anon_insert" on public."signal_snapshots" for insert to anon with check (true);');
P('');

// ── user_watchlist ──────────────────────────────────────────────────────────
P('-- user_watchlist: rows are scoped to a client-generated session id held in');
P('-- localStorage. This is obscurity, not authentication — anyone reading the');
P('-- uuid out of devtools can read or delete that session. Reproduced as-is');
P('-- because the app has no auth system to key on (see src/pages/Home/index.tsx).');
P('grant select, insert, delete on public."user_watchlist" to anon;');
P('drop policy if exists "user_watchlist_anon_all" on public."user_watchlist";');
P('create policy "user_watchlist_anon_read" on public."user_watchlist" for select to anon using (true);');
P('create policy "user_watchlist_anon_insert" on public."user_watchlist" for insert to anon with check (true);');
P('create policy "user_watchlist_anon_delete" on public."user_watchlist" for delete to anon using (true);');
P('');

P('commit;');
P('');

fs.writeFileSync(outPath, out.join('\n'));
console.log(`wrote ${outPath}`);
console.log(`tables secured: ${Object.keys(defs).length}`);
